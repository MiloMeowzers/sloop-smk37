"""The SMK-37 vocoder's filter banks (firmware/src/smk_vocoder.h): writes firmware/src/smk_vocoder_tab.h.

20 bands at the Sennheiser VSM201's channel centres (read off its manual's Illustration 8, the filter responses;
channel 6 at 705 Hz, the manual's "approximately 700 Hz"), their -3 dB bandwidth the distance to their neighbours (log),
so neighbours cross ~3 dB down as the VSM201's curves do near their tops. Both banks (analysis, the voice's envelopes;
synthesis, the carrier) 4th order: two equal band-pass sections (RBJ, constant 0 dB peak gain) each wider by
1 / sqrt(sqrt(2) - 1), so the pair keeps that bandwidth and its skirts fall 12 dB an octave. 2nd order leaked: a 1 kHz
voice opened the low bands at -17 dB, and the bands near 1 kHz passed a sawtooth carrier's fundamental (9 x its
harmonic there) at -38 dB, so the fundamental came out only 6 dB under the harmonic the voice asked for.
The bank runs at 22050 Hz (the VSM201's range is 100 Hz - 8 kHz): the voice and the carrier go down 2:1 and the output
up 2:1 through a half-band FIR (HB taps, Q15, its zero taps left out). Coefficients Q30. Also the envelopes' and the
voiced / unvoiced detector's one-pole coefficients (Q16), at 22050 Hz.

Also (2026-11-01, smk37-devtools vocoder-ui-spec.md §7): the VSM201's NORMAL weights (its schematic B11/B12, the fixed
resistor of each channel into the NORMAL summing amplifier, 9.53k feedback: ch1 2.94k .. ch20 10.0k), folded into the
synthesis bank's first section (VOC_B0S: no cost a sample); the bridge's TILT (the owner's addition, beyond the
VSM201) as per band gains for each step; the carrier AGC's detector.

    python3 tools/gen_vocoder.py > firmware/src/smk_vocoder_tab.h
"""
import math

FS = 22050.0
F = [145, 250, 350, 465, 580, 705, 840, 980, 1120, 1290,
     1490, 1710, 2030, 2370, 2740, 3260, 3840, 4560, 5570, 6780]
# the NORMAL resistors (kOhm), ch1 .. ch20, read off the VSM201 schematic (JL11025 page 0, Kanalpegelung B11 / B12):
# R11, R21, R31 .. R201; the channel's gain into the NORMAL bus 9.53k / R
NORMAL_R = [2.94, 3.48, 3.74, 3.92, 4.12, 4.42, 4.64, 4.87, 5.23, 5.49,
            5.76, 6.19, 6.49, 6.98, 7.32, 7.87, 8.25, 8.66, 9.31, 10.0]
TILT_STEPS = 13                   # the bridge's TILT: -3 .. +3 dB an octave in 0.5 dB steps (index 6: flat)
TILT_PIVOT = 1000.0               # Hz: the band gains 1 there
HB_HALF = 7                       # the half-band's taps: h[0] and h[+-1], h[+-3] .. h[+-(2 HB_HALF - 1)]
HB_BETA = 7.0


def onepole_q16(fc):
    return round((1.0 - math.exp(-2.0 * math.pi * fc / FS)) * 65536.0)


def bessel_i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2.0 * k)) ** 2
        s += t
        k += 1
    return s


def halfband():
    """the odd taps h[1], h[3] .. (h[0] = 1/2), Q15, windowed sinc (Kaiser), the pair summing to 1/2"""
    L = 2 * HB_HALF - 1                                   # the last odd tap
    taps = []
    for j in range(HB_HALF):
        n = 2 * j + 1
        w = bessel_i0(HB_BETA * math.sqrt(1.0 - (n / (L + 1.0)) ** 2)) / bessel_i0(HB_BETA)
        taps.append(math.sin(math.pi * n / 2.0) / (math.pi * n) * w)
    s = 2.0 * sum(taps)
    taps = [t * 0.5 / s for t in taps]                    # DC gain exactly 1 (h0 + 2 sum = 1)
    q = [round(t * 32768.0) for t in taps]
    q[0] += 8192 - sum(q)                                 # Q15: the pair's sum exactly 1/2 (16384 / 2)
    return q


def bank(fs):
    """the 20 bands' (centre, bandwidth, B0, C1, A2) at the rate fs, Q30"""
    n = len(F)
    rows = []
    widen = 1.0 / math.sqrt(math.sqrt(2.0) - 1.0)        # two equal sections: the pair's -3 dB width x 0.644
    for k, f in enumerate(F):
        if k == 0:
            bw = math.log2(F[1] / F[0])
        elif k == n - 1:
            bw = math.log2(F[-1] / F[-2])
        else:
            bw = math.log2(F[k + 1] / F[k - 1]) / 2.0
        w0 = 2.0 * math.pi * f / fs
        w = bw * widen
        alpha = math.sin(w0) * math.sinh(math.log(2.0) / 2.0 * w * w0 / math.sin(w0))
        a0 = 1.0 + alpha
        rows.append((f, bw, round(alpha / a0 * (1 << 30)), round(2.0 * math.cos(w0) / a0 * (1 << 30)),
                     round((1.0 - alpha) / a0 * (1 << 30))))
    return rows


def pink_rms(fs, n=1 << 18):
    """Kellet's economy pink filter (smk_vocoder.h, Q15) on white noise at fs: its rms over the white's"""
    import random
    rnd = random.Random(1)
    k = [(32690, 3245), (31556, 9716), (18678, 34494)]   # (as the firmware's, whatever the rate: its poles move)
    st = [0.0, 0.0, 0.0]
    a2 = w2 = 0.0
    for _ in range(n):
        w = rnd.uniform(-1.0, 1.0)
        for i, (p, g) in enumerate(k):
            st[i] = st[i] * p / 32768.0 + w * g / 32768.0
        y = sum(st) + w * 6056 / 32768.0
        a2 += y * y
        w2 += w * w
    return math.sqrt(a2 / w2)


def main():
    n = len(F)
    rows = bank(FS)
    hb = halfband()
    print("/* generated by tools/gen_vocoder.py: do not edit */")
    print("/* the SMK-37 vocoder's bank, at 22050 Hz: the VSM201's 20 channel centres, each band two equal band-pass")
    print(" * sections (RBJ, 0 dB peak), Q30: y = B0 (x - x2) + C1 y1 - A2 y2; the pair's -3 dB bandwidth the distance to")
    print(" * the neighbours (octaves, below). The analysis and the synthesis banks the same */")
    print("#define VOC_NB %du" % n)
    print("#define VOC_FS 22050u")
    print("static const int32_t VOC_B0[VOC_NB] = {" + ", ".join(str(r[2]) for r in rows) + "};")
    print("static const int32_t VOC_C1[VOC_NB] = {" + ", ".join(str(r[3]) for r in rows) + "};")
    print("static const int32_t VOC_A2[VOC_NB] = {" + ", ".join(str(r[4]) for r in rows) + "};")
    print("static const uint16_t VOC_FC[VOC_NB] = {" + ", ".join(str(r[0]) for r in rows) + "};   /* Hz */")
    print("/* bandwidths (octaves): " + ", ".join("%.2f" % r[1] for r in rows) + " */")
    print("/* the 2:1 half-band FIR (44100 <-> 22050): h[0] = 1/2, h[+-1], h[+-3] .. Q15 (Kaiser %.0f); the rest zero */"
          % HB_BETA)
    print("#define VOC_HB %du" % HB_HALF)
    print("static const int32_t VOC_HBT[VOC_HB] = {" + ", ".join(str(t) for t in hb) + "};")
    print("#define VOC_ENV_ATT %du        /* the envelopes' one-pole, Q16: attack ~50 Hz (~3 ms) */" % onepole_q16(50.0))
    print("#define VOC_ENV_REL %du        /* release ~20 Hz (~8 ms): the VSM201's 20 - 50 Hz smoothing */" % onepole_q16(20.0))
    print("#define VOC_LF_K %du          /* the voiced / unvoiced detector's channel 0: a low-pass at 1 kHz */" % onepole_q16(1000.0))
    print("#define VOC_CENV_K %du        /* the carrier's level (for the noise that replaces it): ~50 Hz */" % onepole_q16(50.0))
    # NORMAL: each channel's gain 1 / R, scaled so the 20 have an rms of 1 (a flat spectrum keeps its level)
    g = [1.0 / r for r in NORMAL_R]
    rms = math.sqrt(sum(x * x for x in g) / n)
    g = [x / rms for x in g]
    print("/* the VSM201's NORMAL weights (B11 / B12: 9.53k / R, R = %s kOhm), rms 1 over the 20: ch1 %+.1f dB, ch20 %+.1f dB;"
          % (", ".join("%.2f" % r for r in NORMAL_R), 20 * math.log10(g[0]), 20 * math.log10(g[-1])))
    print(" * VOC_B0S = VOC_B0 x the weight: the synthesis bank's first section (the analysis keeps VOC_B0) */")
    print("static const int32_t VOC_NORM_Q12[VOC_NB] = {" + ", ".join(str(round(x * 4096)) for x in g) + "};")
    print("static const int32_t VOC_B0S[VOC_NB] = {" + ", ".join(str(round(r[2] * x)) for r, x in zip(rows, g)) + "};")
    # the bridge's TILT: band k's gain 2^(slope x octaves from the pivot / 6.02), slope -3 .. +3 dB an octave
    print("/* the bridge's TILT (the owner's, beyond the VSM201): %d steps, -3 .. +3 dB an octave (0.5 dB), about %.0f Hz;"
          % (TILT_STEPS, TILT_PIVOT))
    print(" * a band's gain, Q12 */")
    print("#define VOC_TILT_N %du" % TILT_STEPS)
    print("#define VOC_TILT_FLAT %du" % (TILT_STEPS // 2))
    print("static const uint16_t VOC_TILT_Q12[VOC_TILT_N][VOC_NB] = {")
    for t in range(TILT_STEPS):
        slope = (t - TILT_STEPS // 2) * 0.5
        row = [round(4096 * 10 ** (slope * math.log2(f / TILT_PIVOT) / 20.0)) for f in F]
        print("    {" + ", ".join(str(x) for x in row) + "},   /* %+.1f dB an octave */" % slope)
    print("};")
    print("#define VOC_AGC_LVL %du       /* the carrier AGC's level: mean |x|, a one-pole of ~20 ms, Q16 a 22.05 kHz sample */"
          % round((1.0 - math.exp(-1.0 / (0.020 * FS))) * 65536.0))
    print("#define VOC_AGC_DN %du       /* .. its gain down ~5 ms, Q16 a block of 16 samples (CTL 32 at 44.1 kHz) */"
          % round((1.0 - math.exp(-16.0 / (0.005 * FS))) * 65536.0))
    print("#define VOC_AGC_UP %du         /* .. and back up ~150 ms */" % round((1.0 - math.exp(-16.0 / (0.150 * FS))) * 65536.0))
    # HQ (vocoder-ui-spec.md §7i-2): the synthesis at 44100 Hz, no 2:1 (the analysis stays at 22050: its envelopes
    # are smooth, and the speech addition's bands end at ~8 kHz)
    hq = bank(2.0 * FS)
    print("/* HQ (SETUP VOC + DRUMS, VOC + SYNTH, VOC ALONE): the synthesis bank at 44100 Hz, the same bands; its NORMAL")
    print(" * weights; the per-sample one-poles at 44100 Hz */")
    print("static const int32_t VOC_B0H[VOC_NB] = {" + ", ".join(str(r[2]) for r in hq) + "};")
    print("static const int32_t VOC_C1H[VOC_NB] = {" + ", ".join(str(r[3]) for r in hq) + "};")
    print("static const int32_t VOC_A2H[VOC_NB] = {" + ", ".join(str(r[4]) for r in hq) + "};")
    print("static const int32_t VOC_B0SH[VOC_NB] = {" + ", ".join(str(round(r[2] * x)) for r, x in zip(hq, g)) + "};")
    print("#define VOC_CENV_KH %du       /* the carrier's level, ~50 Hz, a 44.1 kHz sample */"
          % round((1.0 - math.exp(-2.0 * math.pi * 50.0 / (2.0 * FS))) * 65536.0))
    print("#define VOC_AGC_LVLH %du       /* the carrier AGC's level, ~20 ms, a 44.1 kHz sample */"
          % round((1.0 - math.exp(-1.0 / (0.020 * 2.0 * FS))) * 65536.0))
    print("#define VOC_SOFT_AH %d         /* the SOFT noise's one-pole, ~200 Hz at 44.1 kHz, Q15 */"
          % round(math.exp(-2.0 * math.pi * 200.0 / (2.0 * FS)) * 32768.0))
    print("#define VOC_PINK_Q15H %d        /* the pink filter's rms over white at 44.1 kHz: %.2f: back to 1 */"
          % (round(32768.0 / pink_rms(2.0 * FS)), pink_rms(2.0 * FS)))


if __name__ == "__main__":
    main()
