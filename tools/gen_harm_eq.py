"""The harmoniser's feedback EQ (firmware/src/smk_harm.h, Stage 1b): writes firmware/src/smk_harm_eq.h.

The H949's FEEDBACK GROUP LOW EQ and HIGH EQ (its manual p.3-4 and the curves on p.12): LOW a shelf below ~500 Hz, about
+18 / -12 dB at 100 Hz; HIGH from ~1.5 kHz, a boost of +4 dB above 3 kHz, a cut to about -11 dB at 10 kHz. Here two RBJ
shelving biquads (S = 1) at the harmoniser memory's rate, 22050 Hz: LOW a low shelf at 400 Hz, -12 .. +18 dB in 1 dB
steps (step 12 flat); HIGH a high shelf at 4 kHz, -12 .. +4 dB in 1 dB steps (step 12 flat). Coefficients Q28 (b0, b1,
b2, a1, a2; a0 = 1), the denominator's sign as y = b.x - a.y. Also, for FB LIMIT SAFE, each step's peak gain over all
frequencies (the shelf's full gain when it boosts, 1 when it cuts), Q12, so the loop can be scaled under unity at its
loudest frequency whatever the EQ.

    python3 tools/gen_harm_eq.py > firmware/src/smk_harm_eq.h
"""
import math

FS = 22050.0
LOW_F, LOW_MIN, LOW_MAX = 400.0, -12, 18
HIGH_F, HIGH_MIN, HIGH_MAX = 4000.0, -12, 4
Q = 28


def shelf(f0, gdb, high):
    """RBJ cookbook shelving filter, S = 1: (b0, b1, b2, a1, a2), a0 normalised to 1"""
    a = 10 ** (gdb / 40.0)
    w = 2 * math.pi * f0 / FS
    cw, sw = math.cos(w), math.sin(w)
    s = 1.0                                             # the shelf slope (S = 1: the steepest without a bump)
    al = sw / 2 * math.sqrt((a + 1 / a) * (1 / s - 1) + 2)
    sa = 2 * math.sqrt(a) * al
    if not high:
        b0 = a * ((a + 1) - (a - 1) * cw + sa)
        b1 = 2 * a * ((a - 1) - (a + 1) * cw)
        b2 = a * ((a + 1) - (a - 1) * cw - sa)
        a0 = (a + 1) + (a - 1) * cw + sa
        a1 = -2 * ((a - 1) + (a + 1) * cw)
        a2 = (a + 1) + (a - 1) * cw - sa
    else:
        b0 = a * ((a + 1) + (a - 1) * cw + sa)
        b1 = -2 * a * ((a - 1) + (a + 1) * cw)
        b2 = a * ((a + 1) + (a - 1) * cw - sa)
        a0 = (a + 1) - (a - 1) * cw + sa
        a1 = 2 * ((a - 1) - (a + 1) * cw)
        a2 = (a + 1) - (a - 1) * cw - sa
    return [b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0]


def resp(c, f):
    z = complex(math.cos(2 * math.pi * f / FS), math.sin(2 * math.pi * f / FS))
    zi = 1 / z
    return abs((c[0] + c[1] * zi + c[2] * zi * zi) / (1 + c[3] * zi + c[4] * zi * zi))


def table(name, f0, lo, hi, high):
    rows, peaks = [], []
    for g in range(lo, hi + 1):
        c = shelf(f0, g, high)
        q = [int(round(x * (1 << Q))) for x in c]
        assert all(abs(x) < (1 << 31) for x in q), (name, g, c)
        if g == 0:
            q = [1 << Q, 0, 0, 0, 0]
        pk = max(resp(c, f) for f in [10 * 1.02 ** k for k in range(400)] if f < FS / 2)
        peaks.append(max(4096, int(math.ceil(pk * 4096))))
        rows.append(q)
    print(f"static const int32_t {name}[{len(rows)}][5] = {{")
    for g, q in zip(range(lo, hi + 1), rows):
        print(f"    {{{', '.join(str(x) for x in q)}}},   /* {g:+d} dB */")
    print("};")
    print(f"static const uint16_t {name}_PK[{len(peaks)}] = {{{', '.join(str(p) for p in peaks)}}};")


print("/* SPDX-License-Identifier: GPL-3.0-only */")
print("/* generated by tools/gen_harm_eq.py: the harmoniser's feedback EQ (smk_harm.h). Do not edit. */")
print(f"#define HM_EQ_Q {Q}")
print(f"#define HM_LOW_N {LOW_MAX - LOW_MIN + 1}    /* LOW: {LOW_MIN} .. +{LOW_MAX} dB at {LOW_F:.0f} Hz, step {-LOW_MIN} flat */")
print(f"#define HM_LOW_0 {-LOW_MIN}")
print(f"#define HM_HIGH_N {HIGH_MAX - HIGH_MIN + 1}   /* HIGH: {HIGH_MIN} .. +{HIGH_MAX} dB at {HIGH_F:.0f} Hz, step {-HIGH_MIN} flat */")
print(f"#define HM_HIGH_0 {-HIGH_MIN}")
table("HM_LOW", LOW_F, LOW_MIN, LOW_MAX, False)
table("HM_HIGH", HIGH_F, HIGH_MIN, HIGH_MAX, True)
# INPUT LEVEL (the page's G2 K1): step 0 off, 1 .. 53 = -40 .. +12 dB in 1 dB steps (41: 0 dB, exactly 4096), Q12
INL = [0] + [int(round(4096 * 10 ** ((k - 41) / 20.0))) for k in range(1, 54)]
assert INL[41] == 4096
print(f"#define HM_INL_N {len(INL)}    /* INPUT LEVEL: 0 off, 1 .. 53 = -40 .. +12 dB */")
print("#define HM_INL_0 41")
print(f"static const uint16_t HM_INL[{len(INL)}] = {{{', '.join(str(x) for x in INL)}}};")
# a check, printed as a comment: the gains at 100 Hz and 10 kHz at the extremes
for nm, f0, g, hi, f in (("LOW", LOW_F, 18, False, 100), ("LOW", LOW_F, -12, False, 100),
                         ("HIGH", HIGH_F, 4, True, 6000), ("HIGH", HIGH_F, -12, True, 10000)):
    print(f"/* {nm} {g:+d} dB: {20 * math.log10(resp(shelf(f0, g, hi), f)):+.1f} dB at {f} Hz */")
